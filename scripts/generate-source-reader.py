"""Offline, deterministic native presentation derivative of reviewed source HTML.

No parser dependency, network, importer, archive extraction or original mutation.
Only a viewport in <head> and missing indexed-element ids are inserted. --check
requires every generated byte and catalog pin to match the resident inputs.
"""
import argparse
import hashlib
import json
import re
import stat
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BOOKS = ['republic', 'meditations', 'genealogy-of-morals', 'apology', 'odyssey', 'divine-comedy', 'hamlet', 'relativity']
CATALOG = ROOT / 'lib/books/source-reader-catalog.json'
VIEWPORT = '<meta name="viewport" content="width=device-width, initial-scale=1">'
MAX_DOCUMENT = 2 * 1024 * 1024
MAX_ASSET = 512 * 1024
MAX_TOTAL = 32 * 1024 * 1024


def resident(path):
    info = path.lstat()
    assert stat.S_ISREG(info.st_mode) and not stat.S_ISLNK(info.st_mode) and (not info.st_size or info.st_blocks), str(path)
    return info


def read(path):
    resident(path)
    return path.read_bytes()


def sha(value):
    return hashlib.sha256(value).hexdigest()


class Coordinates(HTMLParser):
    def __init__(self, text):
        super().__init__(convert_charrefs=False)
        self.text = text
        self.lines = [0]
        self.lines.extend(i + 1 for i, c in enumerate(text) if c == '\n')
        self.ids = set()
        self.blocks = []
        self.head_end = None
        self.heads = 0
        self.resources = []
        self.hrefs = []
        self.feed(text)
        self.close()

    def handle_starttag(self, tag, attrs):
        values = dict(attrs)
        assert len(values) == len(attrs), 'Duplicate source attribute'
        if 'id' in values:
            identity = values['id']
            assert identity and len(identity) <= 200 and re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.:-]*', identity), 'Unsafe source id'
            assert identity not in self.ids, 'Duplicate source id'
            self.ids.add(identity)
        assert tag not in ['script', 'iframe', 'object', 'embed', 'form', 'base', 'link'], 'Active source element'
        assert not any(key.lower().startswith('on') for key in values), 'Active source attribute'
        if tag == 'meta':
            assert values.get('name', '').lower() != 'viewport' and 'http-equiv' not in values, 'Unexpected source meta'
        if tag == 'head':
            self.heads += 1
            line, column = self.getpos()
            self.head_end = self.lines[line - 1] + column + len(self.get_starttag_text())
        if 'data-reading-index' in values:
            index = values['data-reading-index']
            assert index == str(len(self.blocks)), 'Noncanonical reading coordinate'
            line, column = self.getpos()
            start = self.lines[line - 1] + column
            raw = self.get_starttag_text()
            assert self.text[start:start + len(raw)] == raw
            assert not raw.endswith('/>'), 'Self-closing reading coordinate'
            self.blocks.append((int(index), values.get('id'), start + len(raw) - 1))
        if 'src' in values:
            assert tag == 'img', 'Unsupported source resource'
            self.resources.append(values['src'])
        for key in ['srcset', 'poster', 'action', 'formaction', 'data']:
            assert key not in values, 'Unsupported source resource attribute'
        if 'href' in values:
            self.hrefs.append(values['href'])

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)


def derive(source, block_count):
    text = source.decode('utf-8', errors='strict')
    parsed = Coordinates(text)
    assert parsed.heads == 1 and parsed.head_end is not None
    assert len(parsed.blocks) == block_count
    assert all(href.startswith('#') and href[1:] in parsed.ids for href in parsed.hrefs), 'External or unresolved anchor'
    changes = [(parsed.head_end, VIEWPORT)]
    overrides = {}
    for index, original_id, offset in parsed.blocks:
        generated = f'soe-reading-position-{index}'
        assert generated not in parsed.ids, 'Reserved native anchor collision'
        if original_id is not None:
            overrides[str(index)] = original_id
        else:
            changes.append((offset, f' id="{generated}"'))
    derivative = text
    for offset, insertion in sorted(changes, reverse=True):
        derivative = derivative[:offset] + insertion + derivative[offset:]
    # Byte-preserving insertion proof: remove precisely the declared additions.
    restored = derivative
    shift = 0
    positions = []
    for offset, insertion in sorted(changes):
        positions.append((offset + shift, insertion))
        shift += len(insertion)
    for offset, insertion in reversed(positions):
        assert restored[offset:offset + len(insertion)] == insertion
        restored = restored[:offset] + restored[offset + len(insertion):]
    assert restored.encode('utf-8') == source
    resources = parsed.resources + re.findall(r'url\([\"\']?([^\)\"\']+)', text)
    return derivative.encode('utf-8'), overrides, resources


def generate(check):
    pins = {row['bookId']: row for row in json.loads(read(ROOT / 'lib/books/passage-indexes.json'))}
    editions = []
    for book in BOOKS:
        folder = ROOT / 'content/great-books' / book
        manifest = json.loads(read(folder / 'manifest.json'))
        source = read(folder / 'reader.html')
        pin = pins[book]
        assert manifest['bookId'] == book and manifest['editionId'] == pin['editionId']
        assert len(source) == manifest['reader']['bytes']
        assert sha(source) == manifest['reader']['sha256'] == pin['documentSha256']
        assert manifest['reader']['blockCount'] == pin['blockCount']
        derivative, overrides, resources = derive(source, pin['blockCount'])
        assert 0 < len(derivative) <= MAX_DOCUMENT
        assets, urls = [], set()
        for entry in manifest['assets']:
            path = entry['path']
            assert isinstance(path, str) and len(path) <= 300 and re.fullmatch(r'[A-Za-z0-9_./-]+', path)
            assert all(part not in ['', '.', '..'] for part in path.split('/'))
            assert entry['mime'] in ['image/png', 'image/jpeg', 'image/gif', 'image/webp']
            info = resident(folder / 'assets' / path)
            assert 0 < info.st_size == entry['bytes'] <= MAX_ASSET
            assert sha(read(folder / 'assets' / path)) == entry['sha256']
            url = f'/api/great-books/edition/{book}/assets/{path}?sha={entry["sha256"]}'
            assert url not in urls
            urls.add(url)
            assets.append({key: entry[key] for key in ['path', 'sha256', 'bytes', 'mime']})
        assert len(assets) <= 256 and len(derivative) + sum(asset['bytes'] for asset in assets) <= MAX_TOTAL
        assert set(resources) == urls, 'Source resource closure differs from manifest'
        target = folder / 'native-reader.html'
        if check:
            assert read(target) == derivative, f'Stale derivative: {book}'
        else:
            if target.exists():
                resident(target)
            target.write_bytes(derivative)
        editions.append({'bookId': book, 'editionId': pin['editionId'], 'sourceDocumentSha256': pin['documentSha256'],
                         'documentSha256': sha(derivative), 'documentBytes': len(derivative), 'blockCount': pin['blockCount'],
                         'anchorOverrides': overrides, 'assets': assets})
    encoded = (json.dumps({'schemaVersion': 1, 'derivativeVersion': 'source-reader-v1', 'editions': editions}, indent=2, ensure_ascii=False) + '\n').encode()
    if check:
        assert read(CATALOG) == encoded, 'Stale source reader catalog'
    else:
        if CATALOG.exists():
            resident(CATALOG)
        CATALOG.write_bytes(encoded)
    print(json.dumps({'status': 'CHECKED' if check else 'GENERATED', 'editions': len(editions), 'assets': sum(len(e['assets']) for e in editions),
                      'documentBytes': sum(e['documentBytes'] for e in editions), 'catalogSha256': sha(encoded)}, sort_keys=True))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
